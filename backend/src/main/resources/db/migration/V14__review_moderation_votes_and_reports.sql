-- Reviews get a moderation state, helpful votes and shoppers' reports. A hidden review is kept (its author
-- still sees it, marked as not published) but leaves the product's average.

-- NEW: not looked at yet (shown); LIVE: kept by staff; REPORTED: a shopper reported it (shown until staff
-- decide); HIDDEN: taken off the site by staff, with a reason. The default is LIVE so the reviews already
-- here, and the demo catalog's (db/seed), count as kept; ReviewService writes NEW for a shopper's review.
ALTER TABLE product_reviews ADD COLUMN status VARCHAR(10) NOT NULL DEFAULT 'LIVE'
    CHECK (status IN ('NEW', 'LIVE', 'REPORTED', 'HIDDEN'));
ALTER TABLE product_reviews ADD COLUMN hidden_reason VARCHAR(200);
ALTER TABLE product_reviews ADD CONSTRAINT ck_product_reviews_hidden_reason
    CHECK ((status = 'HIDDEN') = (hidden_reason IS NOT NULL));
-- kept equal to the review's rows in review_votes by ReviewService, in the vote's own statement
ALTER TABLE product_reviews ADD COLUMN helpful_count INTEGER NOT NULL DEFAULT 0 CHECK (helpful_count >= 0);

-- The product page lists a product's shown reviews by helpfulness or age; staff list them by state and age.
CREATE INDEX ix_product_reviews_shown ON product_reviews (product_id, helpful_count DESC, created_at DESC)
    WHERE status <> 'HIDDEN';
CREATE INDEX ix_product_reviews_state ON product_reviews (status, created_at);

-- One helpful vote per signed-in shopper per review. There is no "not helpful": a count of those mostly
-- measures disagreement with the reviewer, not the review's use.
CREATE TABLE review_votes (
    review_id  UUID NOT NULL REFERENCES product_reviews (id) ON DELETE CASCADE,
    user_id    UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    PRIMARY KEY (review_id, user_id)
);

-- A shopper's report. Open until staff keep or hide the review; one open report per shopper per review.
CREATE TABLE review_reports (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id   UUID NOT NULL REFERENCES product_reviews (id) ON DELETE CASCADE,
    user_id     UUID REFERENCES users (id) ON DELETE SET NULL,
    reason      VARCHAR(200) NOT NULL CHECK (length(btrim(reason)) > 0),
    created_at  TIMESTAMP NOT NULL DEFAULT NOW(),
    resolved_at TIMESTAMP
);
CREATE UNIQUE INDEX uq_review_reports_open ON review_reports (review_id, user_id) WHERE resolved_at IS NULL;
CREATE INDEX ix_review_reports_review ON review_reports (review_id, created_at DESC);

-- The average and count leave hidden reviews out. Same function as V6, one condition more.
CREATE OR REPLACE FUNCTION refresh_product_rating(target UUID) RETURNS void
LANGUAGE plpgsql AS $$
BEGIN
    PERFORM 1 FROM products WHERE id = target FOR NO KEY UPDATE;

    UPDATE products p
    SET average_rating = r.avg_rating,
        review_count   = r.cnt
    FROM (SELECT round(avg(rating)::numeric, 2) AS avg_rating, count(*)::int AS cnt
          FROM product_reviews
          WHERE product_id = target AND status <> 'HIDDEN') r
    WHERE p.id = target;
END;
$$;

-- Only the columns the average depends on: a helpful vote must not lock the product row and recompute it.
DROP TRIGGER trg_product_reviews_refresh_rating ON product_reviews;
CREATE TRIGGER trg_product_reviews_refresh_rating
AFTER INSERT OR DELETE OR UPDATE OF rating, status, product_id ON product_reviews
FOR EACH ROW EXECUTE FUNCTION product_reviews_refresh_rating();
