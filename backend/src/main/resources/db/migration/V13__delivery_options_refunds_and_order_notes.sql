-- Staff run the shop's delivery: the options and the free-shipping limit move from code into tables.
-- Orders remember the option as it was when placed, get a courier and tracking number, and can be
-- partly refunded. Staff notes and who moved an order are kept with its history.

-- An option's id is what an order stores in shipping_method: the three that were in code keep their names
-- (standard, express, locker), so every order placed before this migration still points at its option.
CREATE TABLE delivery_options (
    id              VARCHAR(40) PRIMARY KEY CHECK (id ~ '^[a-z0-9][a-z0-9-]*$'),
    name            VARCHAR(80) NOT NULL,
    price           NUMERIC(10,2) NOT NULL CHECK (price >= 0),
    -- ordered before this time on a working day, it leaves the same day: "15:00", the shop's own time zone.
    -- Text, not TIME: a wall-clock time has no zone, and the app's UTC JDBC setting would shift a TIME.
    order_by        VARCHAR(5) NOT NULL CHECK (order_by ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
    days_min        SMALLINT NOT NULL CHECK (days_min BETWEEN 0 AND 30),
    days_max        SMALLINT NOT NULL CHECK (days_max BETWEEN 0 AND 30),
    countries       VARCHAR(2)[] NOT NULL,
    active          BOOLEAN NOT NULL DEFAULT TRUE,
    -- free once the order reaches the free-shipping limit
    free_over_limit BOOLEAN NOT NULL DEFAULT FALSE,
    position        INTEGER NOT NULL DEFAULT 0,
    updated_at      TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_delivery_days CHECK (days_max >= days_min),
    CONSTRAINT ck_delivery_countries CHECK (cardinality(countries) > 0
        AND countries <@ ARRAY['EE', 'LV', 'LT', 'FI']::VARCHAR(2)[])
);

