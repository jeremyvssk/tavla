-- Staff roles and the audit log. The roles and what each may do are in auth/StaffArea.java; the
-- admin's own copy of the split is frontend/src/admin/access.ts.

-- SUPPORT runs orders and reviews, SALES the catalog and delivery options, ADMIN everything.
ALTER TABLE users DROP CONSTRAINT users_role_check;
ALTER TABLE users ADD CONSTRAINT users_role_check CHECK (role IN ('CUSTOMER', 'SUPPORT', 'SALES', 'ADMIN'));

-- Shown on the admin's users page; written at every successful sign-in.
ALTER TABLE users ADD COLUMN last_sign_in_at TIMESTAMP;

-- The users page filters staff from customers and counts admins.
CREATE INDEX ix_users_staff ON users (role) WHERE role <> 'CUSTOMER';

-- One row per staff change and per staff sign-in, written in the same transaction as the change.
-- Who: an id and the role at the time, never a name or an email, so the log isn't one more copy of
-- personal data; the page looks the name up when an admin reads it. The address is cut to its first
-- two parts before it is stored.
CREATE TABLE audit_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at            TIMESTAMP NOT NULL DEFAULT NOW(),
    -- null for a refused sign-in nobody owns, and once the account is deleted: the entry stays
    actor_id      UUID REFERENCES users(id) ON DELETE SET NULL,
    actor_role    VARCHAR(10) CHECK (actor_role IN ('SUPPORT', 'SALES', 'ADMIN')),
    kind          VARCHAR(10) NOT NULL CHECK (kind IN ('ORDERS', 'PRODUCTS', 'REVIEWS', 'ACCESS')),
    -- a sentence with {target} where the target's name goes, e.g. "Marked {target} shipped"
    action        VARCHAR(120) NOT NULL,
    target_type   VARCHAR(10) CHECK (target_type IN ('ORDER', 'PRODUCT', 'CATEGORY', 'REVIEW', 'USER', 'DELIVERY', 'IMPORT')),
    target_id     VARCHAR(64),
    target_label  VARCHAR(255),
    change_from   VARCHAR(255),
    change_to     VARCHAR(255),
    detail        VARCHAR(255),
    flag_text     VARCHAR(120),
    flag_serious  BOOLEAN NOT NULL DEFAULT false,
    ip            VARCHAR(64)
);

CREATE INDEX ix_audit_log_at ON audit_log (at DESC);
CREATE INDEX ix_audit_log_actor_at ON audit_log (actor_id, at DESC);

-- Append-only, enforced where no code path can skip it. Nobody updates an entry, admins included.
-- Deleting is allowed only past the 12-month retention (AuditRetention does it nightly). The one
-- update allowed is the foreign key's own ON DELETE SET NULL when a staff account is deleted.
CREATE FUNCTION audit_log_append_only() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW.actor_id IS NULL AND OLD.actor_id IS NOT NULL
           AND to_jsonb(NEW) - 'actor_id' = to_jsonb(OLD) - 'actor_id' THEN
            RETURN NEW;
        END IF;
        RAISE EXCEPTION 'audit_log is append-only';
    END IF;
    IF OLD.at >= NOW() - INTERVAL '12 months' THEN
        RAISE EXCEPTION 'audit_log entries are kept for 12 months';
    END IF;
    RETURN OLD;
END;
$$;

CREATE TRIGGER trg_audit_log_append_only
BEFORE UPDATE OR DELETE ON audit_log
FOR EACH ROW EXECUTE FUNCTION audit_log_append_only();
