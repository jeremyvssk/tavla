-- Orders, their lines and status history, and the Stripe payment behind each one. The statuses and the
-- moves between them are in claude-docs/ORDER_STATES.md; OrderStatus.java is the only code that changes them.
-- Money is NUMERIC(10,2) like products.price; Stripe is sent the same amount in cents.

-- The last line of defence against overselling. The stock is taken by one conditional UPDATE
-- (ProductRepository.reserveStock), and this CHECK makes any code path that tries to go below zero fail.
ALTER TABLE products ADD CONSTRAINT ck_products_stock_not_negative CHECK (stock_quantity >= 0);

-- Order numbers the shopper reads aloud on the phone (TV-10001); the UUID stays internal.
CREATE SEQUENCE order_number_seq START WITH 10001;

CREATE TABLE orders (
    id                UUID PRIMARY KEY,
    number            VARCHAR(12) NOT NULL UNIQUE,
    -- An account's orders go with the account when it is deleted (GDPR hard delete). A guest's order is
    -- found by the SHA-256 of the cart cookie it was placed with, the same hash carts.guest_token_hash keeps.
    user_id           UUID REFERENCES users(id) ON DELETE CASCADE,
    guest_token_hash  VARCHAR(64),
    status            VARCHAR(20) NOT NULL CHECK (status IN ('PENDING_PAYMENT', 'PAYMENT_SUCCESSFUL', 'PAYMENT_FAILED',
                                                           'PROCESSING', 'SHIPPED', 'DELIVERED', 'CANCELLED', 'REFUNDED')),
    -- contact and delivery, as typed at checkout (PlaceOrderRequest has the matching rules)
    email             VARCHAR(255) NOT NULL,
    phone             VARCHAR(32) NOT NULL,
    first_name        VARCHAR(100) NOT NULL,
    last_name         VARCHAR(100) NOT NULL,
    street            VARCHAR(100) NOT NULL,
    flat              VARCHAR(100),
    postcode          VARCHAR(10) NOT NULL,
    city              VARCHAR(100) NOT NULL,
    country           VARCHAR(2) NOT NULL CHECK (country IN ('EE', 'LV', 'LT', 'FI')),
    shipping_method   VARCHAR(10) NOT NULL CHECK (shipping_method IN ('STANDARD', 'EXPRESS', 'LOCKER')),
    -- worked out by OrderTotals when the order is placed, never sent by the browser
    subtotal          NUMERIC(10,2) NOT NULL CHECK (subtotal >= 0),
    shipping_cost     NUMERIC(10,2) NOT NULL CHECK (shipping_cost >= 0),
    -- the VAT inside the total (EU prices include it), shown on the receipt, not added on top
    vat               NUMERIC(10,2) NOT NULL CHECK (vat >= 0),
    total             NUMERIC(10,2) NOT NULL CHECK (total = subtotal + shipping_cost),
    -- until when the reserved stock waits for a payment; null once paid, cancelled or released
    hold_until        TIMESTAMP,
    placed_at         TIMESTAMP NOT NULL DEFAULT NOW(),
    -- when the status last moved; a Stripe event older than this is about an earlier attempt and is ignored
    status_changed_at TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_orders_one_owner CHECK ((user_id IS NULL) <> (guest_token_hash IS NULL))
);

-- the account's order list, newest first (step 7)
CREATE INDEX ix_orders_user_placed ON orders (user_id, placed_at DESC) WHERE user_id IS NOT NULL;
-- OrderExpiry looks every minute for unpaid orders whose hold has run out
CREATE INDEX ix_orders_unpaid_hold ON orders (hold_until) WHERE status IN ('PENDING_PAYMENT', 'PAYMENT_FAILED');

-- A frozen copy of each cart line. The name, options, photo and price are copied, so a later catalog
-- change never rewrites what someone bought.
CREATE TABLE order_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      UUID NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    -- kept to link back to the product and to put stock back. SET NULL: deleting a product from the
    -- catalog must not delete what was bought; the copied columns still say what it was.
    product_id    UUID REFERENCES products(id) ON DELETE SET NULL,
    position      SMALLINT NOT NULL,
    product_name  VARCHAR(255) NOT NULL,
    options       VARCHAR(255),
    image_url     VARCHAR(255),
    image_framing JSONB,
    unit_price    NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
    quantity      INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 10),
    line_total    NUMERIC(10,2) NOT NULL CHECK (line_total = unit_price * quantity),
    UNIQUE (order_id, position)
);

-- One row per status move: the order page's history, and the audit trail of who did what.
CREATE TABLE order_status_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    UUID NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    -- null on the first row, when the order is placed
    from_status VARCHAR(20),
    to_status   VARCHAR(20) NOT NULL,
    actor       VARCHAR(10) NOT NULL CHECK (actor IN ('SHOPPER', 'STRIPE', 'TIMER', 'ADMIN')),
    note        VARCHAR(255),
    created_at  TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE INDEX ix_order_status_history_order ON order_status_history (order_id, id);

-- The Stripe side of an order. One PaymentIntent per order, reused when the shopper tries another card.
-- No card number, expiry or CVC column exists or ever will: Stripe's form sends those straight to Stripe.
-- The brand and last 4 digits are what Stripe hands back, and are safe to show on a receipt.
CREATE TABLE payments (
    id                  UUID PRIMARY KEY,
    order_id            UUID NOT NULL UNIQUE REFERENCES orders(id) ON DELETE CASCADE,
    provider            VARCHAR(20) NOT NULL,
    provider_payment_id VARCHAR(255) NOT NULL UNIQUE,
    amount              NUMERIC(10,2) NOT NULL CHECK (amount >= 0),
    currency            VARCHAR(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    status              VARCHAR(10) NOT NULL CHECK (status IN ('STARTED', 'SUCCEEDED', 'FAILED', 'CANCELED')),
    card_brand          VARCHAR(20),
    card_last4          VARCHAR(4) CHECK (card_last4 ~ '^[0-9]{4}$'),
    -- Stripe's decline code (insufficient_funds, expired_card...), kept to tell the shopper what to do
    failure_code        VARCHAR(50),
    created_at          TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMP NOT NULL DEFAULT NOW()
);

-- Stripe delivers each event at least once, sometimes twice. The event id is written in the same
-- transaction as the order change it causes, so a second delivery finds it and changes nothing.
CREATE TABLE processed_payment_events (
    event_id     VARCHAR(255) PRIMARY KEY,
    type         VARCHAR(100) NOT NULL,
    processed_at TIMESTAMP NOT NULL DEFAULT NOW()
);
