-- Notes the team leaves on an order; the customer never sees them.
CREATE TABLE order_notes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   UUID NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    author_id  UUID REFERENCES users (id) ON DELETE SET NULL,
    note       VARCHAR(1000) NOT NULL CHECK (length(btrim(note)) > 0),
    created_at TIMESTAMP NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_order_notes_order ON order_notes (order_id, id);

-- A part of a delivered (or shipping) order's payment given back: some lines, and the shipping, or both.
-- The whole-order refund of a cancellation stays on the payments row (REFUND_DUE → REFUNDED).
-- status: DUE until Stripe accepts it (RefundRetry asks again), then PENDING or SUCCEEDED.
CREATE TABLE refunds (
    id           UUID PRIMARY KEY,
    order_id     UUID NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    amount       NUMERIC(10,2) NOT NULL CHECK (amount > 0),
    shipping     BOOLEAN NOT NULL,
    reason       VARCHAR(200) NOT NULL CHECK (length(btrim(reason)) > 0),
    status       VARCHAR(10) NOT NULL CHECK (status IN ('DUE', 'PENDING', 'SUCCEEDED')),
    requested_by UUID REFERENCES users (id) ON DELETE SET NULL,
    created_at   TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMP NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_refunds_order ON refunds (order_id);
CREATE INDEX ix_refunds_due ON refunds (updated_at) WHERE status = 'DUE';
-- at most one refund of an order's shipping
CREATE UNIQUE INDEX uq_refunds_order_shipping ON refunds (order_id) WHERE shipping;

CREATE TABLE refund_lines (
    refund_id UUID NOT NULL REFERENCES refunds (id) ON DELETE CASCADE,
    -- the order line, by its position on the order (order_items is unique on order_id + position)
    position  SMALLINT NOT NULL,
    quantity  INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 10),
    amount    NUMERIC(10,2) NOT NULL CHECK (amount >= 0),
    PRIMARY KEY (refund_id, position)
);
